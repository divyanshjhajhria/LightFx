section('Together against alone (public/together.json: our bank with its desks sharing and cancelling, then each on its own)');
const together = JSON.parse(readFileSync('public/together.json', 'utf8')) as TogetherFile;
const two = (n: number) => n.toFixed(2);
fact('together.squares', together.squares.length);
fact('together.seeds', `${together.seeds[0]} to ${together.seeds[together.seeds.length - 1]}`);
fact('together.runs', together.overall.runs);
fact('together.overruns', together.squares.reduce((s, q) => s + q.together.runsOver + q.alone.runsOver, 0));
const teamBlock = (prefix: string, f: TogetherFile['overall']) => {
  fact(`${prefix}.served.together.percent`, `${two(f.together.servedPct)}%`);
  fact(`${prefix}.served.alone.percent`, `${two(f.alone.servedPct)}%`);
  fact(`${prefix}.gain.points`, two(f.gainPoints));
  // One decimal, as on screen: a whole number would round a small gain up.
  fact(`${prefix}.gain.relative`, `${f.gainRelativePct.toFixed(1)}%`);
  fact(`${prefix}.wins`, `${f.togetherServedMore} of ${f.runs}`);
  fact(`${prefix}.shared.perrun`, one(f.together.allowanceShared));
  fact(`${prefix}.cancelled.perrun`, one(f.together.unitsCancelled));
};
teamBlock('together.all', together.overall);
for (const m of MARKETS) teamBlock(`together.${m}`, together.byMarket[m]);

section('A rush at one desk (public/together.json and docs/grant-study.json; minutes 120 to 300, 3 times the customers, 80% selling)');
{
  const rushSq = together.rush!.squares;
  const held = Array.from({ length: 20 }, (_, i) => i + 11);
  const choosing = Array.from({ length: 10 }, (_, i) => i + 1);
  const gain = (pairs: ReturnType<typeof pairsFor>) => {
    const m = rushMeans(pairs);
    return { g: m.rushTogether - m.rushAlone, runs: m.runs, m };
  };
  const up = gain(pairsFor(rushSq.filter((q) => q.stormMinutes === 0), held));
  const down = gain(pairsFor(rushSq.filter((q) => q.stormMinutes > 0), held));
  fact('rush.g.seeds1to10', two(rushG(rushSq, choosing)));
  fact('rush.g.seeds11to30', two(rushG(rushSq, held)));
  fact('rush.g.card', down1(up.g));
  fact('rush.linksup.runs', up.runs);
  fact('rush.linksup.rushdesk.together.percent', `${two(up.m.rushTogether)}%`);
  fact('rush.linksup.rushdesk.alone.percent', `${two(up.m.rushAlone)}%`);
  fact('rush.linksup.wins', `${up.m.rushWins} of ${up.runs}`);
  fact('rush.linksdown.gain.points', two(down.g));
  fact('rush.linksdown.card', down1(down.g));
  fact('rush.linksdown.runs', down.runs);
  for (const m of ['rush-mars', 'rush-earth'] as const) {
    for (const storm of [0, 120, 360]) {
      const g = gain(pairsFor(rushSq.filter((q) => q.market === m && q.stormMinutes === storm), held));
      fact(`rush.${m.replace('rush-', '')}.storm${storm}.gain.points`, two(g.g));
    }
  }
  const rushAll = rushMeans(pairsFor(rushSq, together.seeds));
  const n = together.overall.runs + rushAll.runs;
  const tAll = (together.overall.together.servedPct * together.overall.runs + rushAll.servedTogether * rushAll.runs) / n;
  const aAll = (together.overall.alone.servedPct * together.overall.runs + rushAll.servedAlone * rushAll.runs) / n;
  fact('rush.allmarkets.gain.card', down1(tAll - aAll));
  fact('rush.allmarkets.runs', n);
  const study = JSON.parse(readFileSync('docs/grant-study.json', 'utf8')) as {
    adopted: boolean;
    chosen: { grantShare: number; grantThreshold: number; grantWaitFactor: number };
    heldOut: { today: { G: number }; chosen: { G: number } };
    gGain: number;
  };
  fact('grants.adopted', study.adopted ? 'yes' : 'no');
  fact('grants.best', `share ${study.chosen.grantShare}, threshold ${study.chosen.grantThreshold}, wait ${study.chosen.grantWaitFactor}`);
  fact('grants.best.heldout.g', two(study.heldOut.chosen.G));
  fact('grants.best.heldout.gain', two(study.gGain));
}

section('Pricing study for our bank (docs/tune-study.json; chosen on seeds 1 to 10, judged on 11 to 40)');
{
  type Row = { gapK: number; alloc: { earth: number; moon: number; mars: number }; served: number; profitMean: number; profitP5: number };
  const t = JSON.parse(readFileSync('docs/tune-study.json', 'utf8')) as {
    adopted: boolean;
    choosing: Row[];
    heldOut: { today: Row; pick: Row };
    mostServed: Row;
    mostServedGainPoints: number;
    mostServedProfitChangePct: number;
  };
  const today = t.choosing.find((r) => r.gapK === DEFAULT_CONFIG.gapK && r.alloc.earth === DEFAULT_CONFIG.alloc.earth && r.alloc.moon === DEFAULT_CONFIG.alloc.moon)!;
  fact('tune.adopted', t.adopted ? 'yes' : 'no');
  fact('tune.today.served.percent', `${two(today.served)}%`);
  fact('tune.today.profit.mean', today.profitMean.toFixed(4));
  fact('tune.mostserved', `gapK ${t.mostServed.gapK}, split ${t.mostServed.alloc.earth} / ${t.mostServed.alloc.moon} / ${t.mostServed.alloc.mars}`);
  fact('tune.mostserved.served.percent', `${two(t.mostServed.served)}%`);
  fact('tune.mostserved.served.gain.points', two(t.mostServedGainPoints));
  fact('tune.mostserved.profit.mean', t.mostServed.profitMean.toFixed(4));
  fact('tune.mostserved.profit.p5', t.mostServed.profitP5.toFixed(4));
  fact('tune.today.profit.p5', today.profitP5.toFixed(4));
  fact('tune.mostserved.profit.change.percent', `${two(t.mostServedProfitChangePct)}%`);
  fact('tune.heldout.today.served.percent', `${two(t.heldOut.today.served)}%`);
}

