// npm run facts: every figure the write-ups use, computed from the code and data as they are now, into docs/facts.md.
// Nothing here is typed in by hand. Re-running it gives the same file.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DEFAULT_CONFIG } from '../src/sim/config';
import { GUIDE_SEED, GUIDE_SEPARATION, GUIDE_WARMUP, Guide } from '../src/sim/guide';
import { lightDelayMin, makeOrbit } from '../src/sim/orbits';
import { MARKETS, MARKET_NAME } from '../src/sim/sweep';
import type { SweepFile } from '../src/sim/sweep';
import { STRATEGIES } from '../src/sim/types';
import type { StrategyId } from '../src/sim/types';
import { Arena } from '../src/sim/world';
import { readResults } from '../src/ui/Presenter';
import { summarise } from '../src/ui/sweepSummary';
import type { Figures } from '../src/ui/sweepSummary';
import { FLOW, MINUTES, SEEDS, nettingStudy } from './nettingStudy';

const lines: string[] = [];
const section = (title: string) => lines.push('', `## ${title}`, '');
const fact = (name: string, value: string | number) => lines.push(`- \`${name}\`: ${value}`);
const int = (n: number) => Math.round(n).toLocaleString('en-GB');
const one = (n: number) => n.toFixed(1);
const BANK: Record<StrategyId, string> = { leased: 'ours', naive: 'oldnews', central: 'askearth' };

// ---- Tests: the runner's own count ------------------------------------------------------------------------------
const dir = mkdtempSync(join(tmpdir(), 'facts-'));
const report = join(dir, 'tests.json');
try {
  execFileSync('npx', ['vitest', 'run', '--reporter=json', `--outputFile=${report}`], { stdio: 'ignore' });
} catch {
  // A failing test still writes the report; the counts below say so.
}
const tests = JSON.parse(readFileSync(report, 'utf8')) as { numTotalTests: number; numPassedTests: number; numTotalTestSuites: number; testResults: unknown[] };
rmSync(dir, { recursive: true, force: true });

// ---- The survival map ---------------------------------------------------------------------------------------------
const sweep = JSON.parse(readFileSync('public/sweep.json', 'utf8')) as SweepFile;
const summary = summarise(sweep);

// ---- The guided demo, scripted: space pressed as soon as each step allows, on a fake clock --------------------------
const arena = new Arena(GUIDE_SEED, { separationDeg: GUIDE_SEPARATION });
arena.run(GUIDE_WARMUP);
const guide = new Guide(arena);
let real = 0;
let marsAtStorm = 0;
let marsAtRecovery = 0;
let seen = '';
const note = () => {
  guide.tick(real);
  if (guide.beat.id !== seen) {
    seen = guide.beat.id;
    if (seen === 'storm') marsAtStorm = arena.worlds.central.desks.mars.served;
    if (seen === 'recovery') marsAtRecovery = arena.worlds.central.desks.mars.served;
  }
};
note();
for (let steps = 0; !guide.finished && steps < 100_000; steps++) {
  if (guide.canAdvance && (guide.beat.advance === 'space' || guide.index === 0)) guide.space();
  note();
  if (guide.finished) break;
  arena.step();
  real += arena.worlds.leased.cfg.dt / guide.speed;
  note();
}
const demo = readResults(arena, guide.trade, marsAtRecovery - marsAtStorm);

// ---- Write ----------------------------------------------------------------------------------------------------------
lines.push(
  '# Facts',
  '',
  'Generated by `npm run facts` (scripts/facts.ts) from the code and data in this repository. Do not edit by hand:',
  'every figure in the write-ups is copied from a line here, exactly as written.',
);

section('Tests');
fact('tests.total', tests.numTotalTests);
fact('tests.passed', tests.numPassedTests);
fact('tests.files', tests.testResults.length);

section('The bank');
fact('limit', DEFAULT_CONFIG.limit);
fact('allowance.earth', DEFAULT_CONFIG.alloc.earth);
fact('allowance.moon', DEFAULT_CONFIG.alloc.moon);
fact('allowance.mars', DEFAULT_CONFIG.alloc.mars);
fact('playsafe.after.minutes', DEFAULT_CONFIG.leaseDuration);
fact('delay.closeapproach.minutes', one(lightDelayMin(makeOrbit(0), 'earth', 'mars')));
fact('delay.farside.minutes', one(lightDelayMin(makeOrbit(150), 'earth', 'mars')));
fact('prices', existsSync('public/earth.json') && (JSON.parse(readFileSync('public/earth.json', 'utf8')) as unknown[]).length >= 2 ? 'real prices replayed' : 'simulated');

section('The survival map (public/sweep.json; storm squares only unless said)');
fact('sweep.squares', sweep.cells.length);
fact('sweep.seedsPerSquare', sweep.seedsPerCell);
fact('sweep.runs.all', int(sweep.totalRuns));
const block = (prefix: string, f: Figures) => {
  fact(`${prefix}.storms`, int(f.runs));
  fact(`${prefix}.steps.millions`, one(f.ticksMillions));
  for (const s of STRATEGIES) {
    const b = f.banks[s];
    fact(`${prefix}.${BANK[s]}.over.storms`, int(b.breachedRuns));
    fact(`${prefix}.${BANK[s]}.over.percent`, `${one(b.breachedPct)}%`);
    fact(`${prefix}.${BANK[s]}.worstpeak.timeslimit`, one(b.worstPeak));
    fact(`${prefix}.${BANK[s]}.served.percent`, `${one(b.servedPct)}%`);
  }
  fact(`${prefix}.ours.marsservedinstorm.perstorm`, one(f.marsServedInStorm.leased));
  fact(`${prefix}.askearth.marsservedinstorm.perstorm`, one(f.marsServedInStorm.central));
};
block('sweep.all', summary.overall);
for (const m of MARKETS) {
  lines.push('', `${MARKET_NAME[m]}:`, '');
  block(`sweep.${m}`, summary.byMarket[m]);
}
fact('sweep.missedcustomers', 'not measured (the sweep records customers served, not why the others were missed)');

section(`The guided demo (seed ${GUIDE_SEED}, scripted: space pressed as soon as each step allows)`);
// The guide's own clock with space pressed at once: the fast-forwarding alone. With the voice-over each line also
// takes as long as it takes to say, which this does not measure.
fact('demo.seconds.withoutvoice', Math.round(real));
fact('demo.ours.over.minutes', one(demo.ours.overMin));
fact('demo.ours.served', demo.ours.served);
fact('demo.oldnews.over.minutes', one(demo.naive.overMin));
fact('demo.askearth.visitortrade', demo.central.outcome);
fact('demo.askearth.marsservedinstorm', demo.central.marsServedInStorm);

section(
  `Netting (our bank, ${MINUTES} minutes of opposite customer flow: sell probability Earth ${FLOW.earth}, Moon ${FLOW.moon}, ` +
    `Mars ${FLOW.mars}; seeds ${SEEDS[0]} to ${SEEDS[SEEDS.length - 1]}; no storm)`,
);
for (const [sep, row] of Object.entries(nettingStudy())) {
  const at = `netting.${sep.replace('°', 'deg')}`;
  fact(`${at}.volume.on`, row['vol on']);
  fact(`${at}.volume.off`, row['vol off']);
  fact(`${at}.change.percent`, `${row['change %']}%`);
  fact(`${at}.onwins`, row['on wins']);
  fact(`${at}.netted.units`, row['netted on']);
  fact(`${at}.over.minutes.on`, row['breach min on']);
  fact(`${at}.over.minutes.off`, row['breach min off']);
}

section('Agents');
const session = 'public/agents/session.json';
fact('agents.session.recorded', existsSync(session) ? 'yes' : 'no');
if (existsSync(session)) {
  const f = JSON.parse(readFileSync(session, 'utf8')) as { recordedWith: string; entries: { directive: unknown }[] };
  fact('agents.session.recordedwith', f.recordedWith);
  fact('agents.session.decisions', f.entries.filter((e) => e.directive).length);
  fact('agents.session.refused', f.entries.filter((e) => !e.directive).length);
}

writeFileSync('docs/facts.md', `${lines.join('\n')}\n`);
console.log(`docs/facts.md: ${lines.filter((l) => l.startsWith('- ')).length} facts.`);
