const lines: string[] = [];
const section = (title: string) => lines.push('', `## ${title}`, '');
const fact = (name: string, value: string | number) => lines.push(`- \`${name}\`: ${value}`);
const int = (n: number) => Math.round(n).toLocaleString('en-GB');
const one = (n: number) => n.toFixed(1);
const BANK: Record<StrategyId, string> = { leased: 'ours', naive: 'oldnews', central: 'askearth' };

// ---- Tests: the runner's own count ------------------------------------------------------------------------------
const dir = mkdtempSync(join(tmpdir(), 'facts-'));
const report = join(dir, 'tests.json');
try {
  execFileSync('npx', ['vitest', 'run', '--reporter=json', `--outputFile=${report}`], { stdio: 'ignore' });
} catch {
  // A failing test still writes the report; the counts below say so.
}
const tests = JSON.parse(readFileSync(report, 'utf8')) as { numTotalTests: number; numPassedTests: number; numTotalTestSuites: number; testResults: unknown[] };
rmSync(dir, { recursive: true, force: true });

// ---- The survival map ---------------------------------------------------------------------------------------------
const sweep = JSON.parse(readFileSync('public/sweep.json', 'utf8')) as SweepFile;
const summary = summarise(sweep);

// ---- The guided demo, scripted: space pressed as soon as each step allows, on a fake clock --------------------------
const arena = new Arena(GUIDE_SEED, { separationDeg: GUIDE_SEPARATION });
arena.run(GUIDE_WARMUP);
const guide = new Guide(arena);
let real = 0;
let marsAtStorm = 0;
let marsAtRecovery = 0;
let seen = '';
const note = () => {
  guide.tick(real);
  if (guide.beat.id !== seen) {
    seen = guide.beat.id;
    if (seen === 'storm') marsAtStorm = arena.worlds.central.desks.mars.served;
    if (seen === 'recovery') marsAtRecovery = arena.worlds.central.desks.mars.served;
  }
};
note();
for (let steps = 0; !guide.finished && steps < 100_000; steps++) {
  if (guide.canAdvance && (guide.beat.advance === 'space' || guide.index === 0)) guide.space();
  note();
  if (guide.finished) break;
  arena.step();
  real += arena.worlds.leased.cfg.dt / guide.speed;
  note();
}
const demo = readResults(arena, guide.trade, marsAtRecovery - marsAtStorm);

// ---- Write ----------------------------------------------------------------------------------------------------------
